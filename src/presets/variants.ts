import raw from './variants.json';
import { parseConfig, type SimConfig } from '../model/config';

export interface VariantMetrics {
  benchmarkFirm: number;
  priceFirm: number;
  priceSpot: number;
  costPerGpuHour: number;
  marginPerGpuHour: number;
  marginAfterCapitalYear: number;
  grossMarginYear: number;
  paybackMonths: number | null;
  pflopHours: number;
  gpuHours: number;
  capexTotal: number;
  binding: 'power' | 'bandwidth' | 'demand';
  cardUtilization: number;
}

export interface BuiltinVariant {
  id: string;
  name: string;
  accelerator: string;
  benchmark: 'gas' | 'cloud';
  config: SimConfig;
  metrics: VariantMetrics;
}

/** Optimized configurations priced just under a competitor benchmark; generated by `npm run variants`. */
export const BUILTIN_VARIANTS: BuiltinVariant[] = (raw as unknown as (Omit<BuiltinVariant, 'config'> & { config: unknown })[]).map((v) => {
  const r = parseConfig(v.config);
  if (!r.ok) throw new Error(`Built-in variant ${v.id} is invalid: ${r.errors.join('; ')}`);
  return { ...v, config: r.config };
});
